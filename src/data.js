// Helper function to get team by name safely
export function getTeamData(teamName) {
  return {
    elo: ELO[teamName] ?? null,
    cn: CN[teamName] ?? null,
    flag: FLAG[teamName] ?? null,
    squad: SQUADS[teamName] ?? null,
    attack: ATTACK_STRENGTH[teamName] ?? null,
    defense: DEFENSE_STRENGTH[teamName] ?? null,
  };
}

// Helper function to get all teams in a group
export function getGroupTeams(group) {
  return GROUPS[group] ?? [];
}

// Helper function to get matches for a group
export function getGroupMatches(group) {
  return SCHEDULE.filter(m => m.group === group);
}

// Helper function to get all completed matches
export function getCompletedMatches() {
  return SCHEDULE.filter(m => m.completed);
}

// Helper function to get upcoming matches
export function getUpcomingMatches() {
  return SCHEDULE.filter(m => !m.completed);
}

// Helper function to get matches by date
export function getMatchesByDate(date) {
  return SCHEDULE.filter(m => m.date === date);
}

// Helper function to get all team names
export function getAllTeams() {
  return Object.keys(ELO);
}

// Helper function to calculate expected score from Elo
export function expectedScore(eloA, eloB) {
  const diff = eloA - eloB;
  return 1 / (1 + Math.pow(10, -diff / 400));
}
